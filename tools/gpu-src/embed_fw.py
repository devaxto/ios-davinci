#!/usr/bin/env python3
"""Embed GMU + SQE firmware into tools/gpu-src/sweet_gpu_fw.h for kernel bring-up.

Sources (gitignored under fw/):
  a630_gmu.bin  - linux-firmware qcom/a630_gmu.bin (a618 legacy GMU)
  a630_sqe.fw   - linux-firmware qcom/a630_sqe.fw  (CP microcode)

Xiaomi vendor copies remain preferred when available via tools/gpu-fw.py.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent
OUT = SRC / "sweet_gpu_fw.h"


def embed_array(name: str, data: bytes, max_size: int) -> tuple[list[str], int]:
    if len(data) == 0 or len(data) > max_size:
        raise SystemExit(f"bad {name} size {len(data)} (max {max_size})")
    if len(data) % 4:
        data = data + b"\0" * (4 - len(data) % 4)
    lines = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        vals = []
        for j in range(0, len(chunk), 4):
            w = int.from_bytes(chunk[j : j + 4], "little")
            vals.append(f"0x{w:08x}u")
        lines.append("\t" + ", ".join(vals) + ",")
    lines.append("};")
    return lines, len(data)


def main() -> None:
    gmu = (ROOT / "fw" / "a630_gmu.bin").read_bytes()
    sqe = (ROOT / "fw" / "a630_sqe.fw").read_bytes()

    gmu_lines, gmu_n = embed_array("sweet_gpu_gmu_fw", gmu, 0x8000)
    sqe_lines, sqe_n = embed_array("sweet_gpu_sqe_fw", sqe, 0x10000)

    lines = [
        "/* Auto-generated by embed_fw.py from fw/a630_gmu.bin + a630_sqe.fw. */",
        "#ifndef _SWEET_GPU_FW_H_",
        "#define _SWEET_GPU_FW_H_",
        "#include <sys/types.h>",
        f"#define SWEET_GPU_GMU_FW_BYTES {gmu_n}u",
        f"#define SWEET_GPU_SQE_FW_BYTES {sqe_n}u",
        "/* Linux adreno_fw_create_bo skips the first 4 bytes of SQE. */",
        "#define SWEET_GPU_SQE_PAYLOAD_OFF 4u",
        f"#define SWEET_GPU_SQE_PAYLOAD_BYTES ({sqe_n}u - SWEET_GPU_SQE_PAYLOAD_OFF)",
        "",
    ]
    lines += gmu_lines
    lines.append("")
    lines += sqe_lines
    lines += ["", "#endif /* _SWEET_GPU_FW_H_ */", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes; gmu={gmu_n} sqe={sqe_n})")


if __name__ == "__main__":
    main()

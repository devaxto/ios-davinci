#!/usr/bin/env python3
"""Embed fw/a630_gmu.bin as tools/gpu-src/sweet_gpu_fw.h for kernel bring-up.

Source: linux-firmware qcom/a630_gmu.bin (redistributable; see fw/manifest.txt).
The Xiaomi vendor copy remains preferred when available via tools/gpu-fw.py.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent
FW = ROOT / "fw" / "a630_gmu.bin"
OUT = SRC / "sweet_gpu_fw.h"


def main() -> None:
    data = FW.read_bytes()
    if len(data) == 0 or len(data) > 0x8000:
        raise SystemExit(f"bad GMU fw size {len(data)}")
    if len(data) % 4:
        data += b"\0" * (4 - len(data) % 4)

    lines = [
        "/* Auto-generated by embed_fw.py from fw/a630_gmu.bin. Do not edit. */",
        "#ifndef _SWEET_GPU_FW_H_",
        "#define _SWEET_GPU_FW_H_",
        "#include <sys/types.h>",
        f"#define SWEET_GPU_GMU_FW_BYTES {len(data)}u",
        "static const uint32_t sweet_gpu_gmu_fw[] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        vals = []
        for j in range(0, len(chunk), 4):
            w = int.from_bytes(chunk[j : j + 4], "little")
            vals.append(f"0x{w:08x}u")
        lines.append("\t" + ", ".join(vals) + ",")
    lines += ["};", "#endif /* _SWEET_GPU_FW_H_ */", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(data)} fw bytes)")


if __name__ == "__main__":
    main()
